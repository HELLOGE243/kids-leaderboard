/**
 * Regenerates src/data/wordsEn.js, the dictionary Word Hunt checks a traced
 * word against.
 *
 *   node scripts/build-words-en.mjs
 *
 * Word Hunt used to accept only the words the model happened to list when it
 * generated the grid. That list is always a fraction of what a 4x4 grid
 * actually contains, so a student tracing a perfectly good word was told it
 * was not a word - which is the complaint that prompted this.
 *
 * The grid already guarantees a traced word is spellable on it. All that is
 * missing is "and it is English", which is what this provides.
 *
 * Words are 3 to 8 letters, which is the useful range on a 4x4 board, and are
 * packed into one string per length so no separators are stored. The result is
 * imported on demand by the game, never by the main bundle.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dict = join(root, 'node_modules', 'wordnet-db', 'dict')

const byTag = {}
const all = new Set()
for (const file of ['index.noun', 'index.verb', 'index.adj', 'index.adv']) {
  const tag = file.split('.')[1]
  for (const line of readFileSync(join(dict, file), 'utf8').split('\n')) {
    if (line.startsWith('  ')) continue
    const w = line.split(' ')[0]
    if (/^[a-z]+$/.test(w)) {
      ;(byTag[tag] = byTag[tag] || new Set()).add(w)
      all.add(w)
    }
  }
}

const MIN = 3
const MAX = 8
const keep = new Set([...all].filter((w) => w.length >= MIN && w.length <= MAX))

// WordNet indexes headwords, so plurals are missing and a child tracing CARDS
// would be told it is not a word. A plain -s, except after a sibilant where
// English wants -es.
const nounsAndVerbs = new Set([...(byTag.noun || []), ...(byTag.verb || [])])
for (const w of nounsAndVerbs) {
  if (w.length >= MIN - 1 && w.length < MAX && !/[sxzh]$/.test(w)) {
    keep.add(w + 's')
  }
}

// Short words a board throws up constantly that a thesaurus does not index.
const SUPPLEMENT = `
ran sat ate got had has her him his its our out she the and for are but not you
was were been have does did had the you who why how its own too any all one two
ten ago off via per yes yet let lot new old big red top end run sun fun bun pun
ill odd owe owl ode oak oar ohm orb eve ewe eel elf elk emu era urn use ump
went came took gave made said told kept held left felt knew grew drew flew
`.split(/\s+/).filter((w) => w.length >= MIN && w.length <= MAX)
for (const w of SUPPLEMENT) keep.add(w)

const groups = {}
for (const w of [...keep].sort()) (groups[w.length] = groups[w.length] || []).push(w)

const lengths = Object.keys(groups).map(Number).sort((a, b) => a - b)
const entries = lengths.map((L) => `  ${L}: ${JSON.stringify(groups[L].join(''))},`).join('\n')
const total = Object.values(groups).reduce((n, g) => n + g.length, 0)

const out = `/**
 * English words of ${MIN} to ${MAX} letters, for validating a traced Word Hunt word.
 *
 * Generated by scripts/build-words-en.mjs from the WordNet index in this
 * project's dependencies, plus regular plurals and a short supplement of the
 * everyday words a dictionary of headwords leaves out. Do not edit by hand.
 *
 * One packed string per word length, so no separators are stored: within a
 * group every word is the same length and can be sliced out. ${total} words.
 * Imported on demand by the game, not by the main bundle.
 */
const PACKED = {
${entries}
}

const BY_LENGTH = {}
for (const [len, packed] of Object.entries(PACKED)) {
  const L = Number(len)
  const set = new Set()
  for (let i = 0; i < packed.length; i += L) set.add(packed.slice(i, i + L))
  BY_LENGTH[L] = set
}

/** Is this an English word we are prepared to accept? */
export function isEnglishWord(word) {
  const w = String(word || '').toLowerCase()
  const set = BY_LENGTH[w.length]
  return set ? set.has(w) : false
}

export const WORD_COUNT = ${total}
`

mkdirSync(join(root, 'src', 'data'), { recursive: true })
writeFileSync(join(root, 'src', 'data', 'wordsEn.js'), out)
console.log(
  `wrote src/data/wordsEn.js: ${total} words, ${Math.round(out.length / 1024)} KB`
  + ` (${Math.round(gzipSync(Buffer.from(out)).length / 1024)} KB gzipped)`
)
for (const L of lengths) console.log(`  ${L} letters: ${groups[L].length}`)
