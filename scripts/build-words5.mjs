/**
 * Regenerates src/data/words5.js, the dictionary the daily Wordle checks a
 * guess against.
 *
 *   node scripts/build-words5.mjs
 *
 * The source is the WordNet index already present in node_modules. Its index
 * files list headwords only, so plurals and irregular past tenses are absent;
 * a player who types ZONES or KNELT is not making them up, and being told a
 * real word is not a word is the single most irritating thing a word game can
 * do. Hence the two additions below: regular plurals derived from four-letter
 * nouns and verbs, and a hand-written supplement.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const dict = join(root, 'node_modules', 'wordnet-db', 'dict')

const byTag = {}
const all = new Set()
for (const file of ['index.noun', 'index.verb', 'index.adj', 'index.adv']) {
  const tag = file.split('.')[1]
  for (const line of readFileSync(join(dict, file), 'utf8').split('\n')) {
    if (line.startsWith('  ')) continue // the licence header
    const w = line.split(' ')[0]
    if (/^[a-z]+$/.test(w)) {
      ;(byTag[tag] = byTag[tag] || new Set()).add(w)
      all.add(w)
    }
  }
}

const five = new Set([...all].filter((w) => w.length === 5).map((w) => w.toUpperCase()))

// A four-letter noun or verb takes a plain -s unless it ends in a sibilant,
// where English wants -es and the result would be six letters anyway.
const nounsAndVerbs = new Set([...(byTag.noun || []), ...(byTag.verb || [])])
for (const w of nounsAndVerbs) {
  if (w.length === 4 && !/[sxzh]$/.test(w)) five.add((w + 's').toUpperCase())
}

const SUPPLEMENT = `
THEIR WHICH WOULD COULD SHALL WHERE THESE THOSE DOING WHOSE AMONG SINCE UNTIL
KNELT DWELT WRUNG OUGHT VOILA WROTE SHOWN CHOSE AROSE DRAWN GROWN THREW BLOWN
FLOWN SWORN WOVEN BOUND FOUND WOUND SPENT DEALT MEANT BUILT SLEPT CREPT SWEPT
LEAPT BURNT LEARN SPELT SMELT SPILT STOOD HEARD BEGUN CLUNG FLUNG STUNG SWUNG
DRUNK STUCK SHOOK SPOKE BROKE AWOKE STOLE FROZE DROVE THROW STRIVE
CRIED SPIED TRIES CRIES SKIES DRIED FRIED FLIES
`.split(/\s+/).filter((w) => w.length === 5)
for (const w of SUPPLEMENT) five.add(w)

const words = [...five].sort()
const packed = words.join('')

const out = `/**
 * Five-letter words the daily Wordle will accept as a guess.
 *
 * Generated by scripts/build-words5.mjs from the WordNet index that already
 * ships in this project's dependencies, plus regular plurals and a supplement
 * of the irregular forms a dictionary of headwords leaves out. Do not edit by
 * hand; edit the script and run it again.
 *
 * Stored as one run of characters rather than an array of strings: every word
 * is exactly five letters, so separators and quotes would be most of the
 * payload. ${words.length} words.
 */
const PACKED = '${packed}'

/** @type {Set<string>} */
export const ALLOWED_GUESSES = new Set()
for (let i = 0; i < PACKED.length; i += 5) ALLOWED_GUESSES.add(PACKED.slice(i, i + 5))

export function isRealWord(word) {
  return ALLOWED_GUESSES.has(String(word || '').toUpperCase())
}
`

mkdirSync(join(root, 'src', 'data'), { recursive: true })
writeFileSync(join(root, 'src', 'data', 'words5.js'), out)
console.log(`wrote src/data/words5.js: ${words.length} words, ${Math.round(out.length / 1024)} KB`)
